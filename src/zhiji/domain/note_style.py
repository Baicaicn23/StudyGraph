"""Markdown 学习笔记写作规范（领域规则，纯文本）。

Agent 的三条写笔记路径——`save_note` 工具沉淀、图片视觉转写（image_notes）、
对话回复本身——共用这一份规范，保证写进知识库的每一篇笔记排版一致、
面向复习讲解。这里只放"怎么写"，不碰模型调用。
"""

from __future__ import annotations

NOTE_STYLE_GUIDE = """【Markdown 笔记写作规范——写进知识库的内容必须遵守】
一、结构骨架：全文只有 1 个 H1 标题（笔记题目本身）；正文用 H2 分节，
固定按「定义 → 要点 → 例子 → 易错点 → 口语说法对照」的顺序组织（没有的小节省略，
不要硬凑）；每节内先给一句加粗的结论，再展开细节——复习时扫一眼加粗句就能过完全篇。
二、讲解导向：定义给「一句话版本 + 精确版本」；例子必须具体（带数字或真实情境）；
易错点用引用块（> ⚠️ …）呈现；学生容易口语化的说法，用「口语说法对照」小节，
格式：- 「大白话说法」 → 术语。
三、排版细节：
- 数学公式一律用 LaTeX：行内 $...$，独立公式用 $$...$$，不要用 x^2 这种纯文本；
- 对比类内容用 Markdown 表格（表头短、每格不超过一行）；
- 代码/算式推导用代码块；列表最多两层嵌套，超过就拆小节；
- 关键词加粗，但每段不超过 2 处——全篇都是加粗等于没有加粗；
- 不用 emoji 装饰标题；不写「综上所述」「以上就是」这类收尾废话；
- 结尾固定加一节「自测三问」：针对本篇内容出 3 个自测问题（只给问题不给答案）。"""

